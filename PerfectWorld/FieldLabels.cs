    private static string Prettify(string field)
    {
        string spaced = System.Text.RegularExpressions.Regex.Replace(field, @"([a-z0-9])([A-Z])", "$1_$2");
        var parts = spaced.Split('_', StringSplitOptions.RemoveEmptyEntries).Select(p =>
        {
            string key = p.ToLowerInvariant();
            if (Tokens.TryGetValue(key, out var text) || FieldLexicon.TryGet(key, out text)) return text;
            if (System.Text.RegularExpressions.Regex.IsMatch(key, @"^v[0-9]+$")) return "版本 " + key[1..];
            var numbered = System.Text.RegularExpressions.Regex.Match(key, @"^([a-z]+)([0-9]+)$");
            if (numbered.Success && (Tokens.TryGetValue(numbered.Groups[1].Value, out text) || FieldLexicon.TryGet(numbered.Groups[1].Value, out text)))
                return text + " " + numbered.Groups[2].Value;
            if (System.Text.RegularExpressions.Regex.IsMatch(key, @"^[a-z]$")) return p.ToUpperInvariant();
            return System.Text.RegularExpressions.Regex.IsMatch(p, @"[A-Za-z]") ? "原始标识（" + p + "）" : p;
        });
        var s = string.Join(" ", parts);
        return s.Length == 0 ? field : char.ToUpper(s[0]) + s[1..];
    }
