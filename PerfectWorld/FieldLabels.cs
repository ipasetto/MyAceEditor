    private static readonly ConcurrentDictionary<string, string> LabelCache = new(StringComparer.Ordinal);
    public static string Label(string field) => LabelCache.GetOrAdd(field, CreateLabel);

    private static string CreateLabel(string field)
    {
        if (Map.TryGetValue(field, out var l)) return l;
        // addons/rands/uniques: "addons_3_id_addon" -> "Atributo 3 (id)" / "..._probability..." -> "Atributo 3 (chance)"
        var m = System.Text.RegularExpressions.Regex.Match(field, @"^(addons|rands|uniques)_(\d+)_(id|probability)");
        if (m.Success)
        {
            string kind = m.Groups[1].Value switch { "addons" => "附加属性", "rands" => "随机属性", _ => "独有属性" };
            string what = m.Groups[3].Value == "id" ? "编号" : "概率";
            return $"{kind} {m.Groups[2].Value}（{what}）";
        }
        return Prettify(field);
    }

    public static string Group(string field)
    {
        string f = field.ToLowerInvariant();
        if (f is "id" or "name" or "realname" || f.StartsWith("id_") || f == "level" || f == "character_combo_id") return "基本";
        if (f.StartsWith("require")) return "需求条件";
        if (f.StartsWith("damage") || f.Contains("attack")) return "攻击";
        if (f.StartsWith("defence") || f.StartsWith("defense") || f.Contains("magic_defence") || f.Contains("enhance") || f.StartsWith("armor")) return "防御";
        if (f.StartsWith("addons_") || f.StartsWith("rands_") || f.StartsWith("uniques_") || f.Contains("probability_addon")) return "属性 / 附加属性";
        if (f.Contains("price") || f.Contains("repair") || f.Contains("decompose") || f.Contains("material")) return "经济";
        if (f.Contains("durability")) return "耐久度";
        if (f.StartsWith("file_")) return "模型 / 文件";
        return "其他";
    }

